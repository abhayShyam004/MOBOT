// The canonical Phase 7 browser fixture: a small deterministic website the
// device driver serves ON the phone with the app's own embedded node (the
// host-side HTML is generated from the same bytes for CI assertions). Serving
// on-device removes the adb-reverse USB tunnel from the browsing path, so the
// WebView fetches 127.0.0.1 from a listener running on the phone itself.
//
// One generator, two consumers (same rule as the MCP fixtures):
//   scripts/test-android-browser.mjs — pushes these pages + the static server
//     onto the phone and runs both under run-as; the WebView browses localhost.
//   server/browser-fixture.test.ts — pins the page contract in CI.
//
// Pages (static bytes; the result page reads its own query string client-side
// so the server needs no templating):
//   index.html    — hero copy, three links, and a form (text input "value"
//                   labelled "Secret word", submit button "Send it") that GETs
//                   result.html, plus data-secret the DOM inspection finds.
//   result.html   — renders "Submitted value: <value>" from ?value=
//   redirect.html — meta-refresh hop to result.html?value=redirected

const INDEX = `<!doctype html><html><head><title>OMB Fixture — Home</title></head>
<body>
<h1>OMB Browser Fixture</h1>
<p data-secret="omb-canary-42">This page is served locally for the Phase 7 browser proof.</p>
<ul id="links">
<li><a id="to-result" href="/result.html?value=first">First link</a></li>
<li><a href="/result.html?value=second">Second link</a></li>
<li><a id="to-redirect" href="/redirect.html">Redirect link</a></li>
</ul>
<form id="the-form" action="/result.html" method="get">
<label for="value">Secret word</label>
<input id="value" name="value" type="text" placeholder="type here">
<button type="submit">Send it</button>
</form>
</body></html>`;

const RESULT = `<!doctype html><html><head><title>OMB Fixture — Result</title></head>
<body><h1>OMB Fixture Result</h1>
<p id="value"></p>
<script>
var params = new URLSearchParams(location.search);
var submitted = params.get("value") || "(none)";
document.getElementById("value").textContent = "Submitted value: " + submitted;
</script>
</body></html>`;

const REDIRECT = `<!doctype html><html><head><meta http-equiv="refresh" content="0; url=/result.html?value=redirected">
<title>OMB Fixture — Redirect</title></head>
<body><p>Redirecting…</p></body></html>`;

/** Static page bytes, keyed by the page the driver asks for. */
export function browserFixtureHtml(page) {
  if (page === "result") return RESULT;
  if (page === "redirect") return REDIRECT;
  return INDEX;
}

/** The three pages, as the driver pushes them (filename → bytes). */
export function browserFixtureFiles() {
  return {
    "index.html": INDEX,
    "result.html": RESULT,
    "redirect.html": REDIRECT,
  };
}

/** The complete on-device fixture server: a generic static file server the
 *  driver pushes to the phone and runs under the app's embedded node with the
 *  directory holding [browserFixtureFiles] and the port to bind. Serves the
 *  byte-identical pages CI asserts on — no templating, no drift. */
export function browserFixtureServerScript() {
  return `#!/usr/bin/env node
// Generated by scripts/lib/omb-browser-fixture.mjs — do not edit by hand.
// argv: <page-dir> <port>
const http = require("http");
const fs = require("fs");
const path = require("path");
const dir = process.argv[2];
const port = Number(process.argv[3]);
http.createServer((req, res) => {
  const name = path.basename(new URL(req.url, "http://127.0.0.1").pathname) || "index.html";
  const file = path.join(dir, name.endsWith(".html") ? name : "index.html");
  try {
    const body = fs.readFileSync(file);
    res.writeHead(200, { "Content-Type": "text/html; charset=utf-8" });
    res.end(body);
  } catch (e) {
    res.writeHead(404, { "Content-Type": "text/plain" });
    res.end("not found");
  }
}).listen(port, "127.0.0.1", () => console.log("fixture-ready:" + port));
`;
}
