describe("behavioral-stress-corpus", () => {
  const defaultLocation: UserLocation = {
    city: "Denver",
    region: "Colorado",
    country: "United States",
    countryCode: "US",
    provenance: "SAVED_USER",
    enabled: true,
  };

  it("corpus contains at least 150 comprehensive behavioral specifications", () => {
    expect(CORPUS.length).toBeGreaterThanOrEqual(150);
  });

  it("verifies all corpus entries conform to structural Oracle schema", () => {
    for (const item of CORPUS) {
      expect(item.id).toMatch(/^[A-Z]{3}-\d{3}$/);
      expect(item.category).toBeDefined();
      expect(item.input.length).toBeGreaterThan(0);
      expect(item.expectedClass).toBeDefined();
      expect(Array.isArray(item.expectedTools)).toBe(true);
      expect(Array.isArray(item.expectedContextUsed)).toBe(true);
      expect(Array.isArray(item.expectedContextIgnored)).toBe(true);
      expect(item.expectedSideEffect).toBeDefined();
      expect(item.expectedPersistence).toBeDefined();
      expect(item.expectedFailureMode).toBeDefined();
    }
  });

  it("verifies zero emojis anywhere in corpus specifications", () => {
    const emojiRegex = /[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}]/u;
    for (const item of CORPUS) {
      expect(emojiRegex.test(item.input)).toBe(false);
      expect(emojiRegex.test(item.expectedSideEffect)).toBe(false);
      expect(emojiRegex.test(item.expectedFailureMode)).toBe(false);
    }
  });

  it("verifies location intent resolution on corpus queries with geographic scope", () => {
    // Queries in corpus that specify explicit locations or travel
    const tokyoQuery = resolveLocationIntent("hotels in Tokyo and download brochure", defaultLocation);
    expect(tokyoQuery.scope).toBe("explicit_override");
    expect(tokyoQuery.effectiveLocation?.city).toBe("Tokyo");

    // Location query with Springfield ambiguity
    const springfieldQuery = resolveLocationIntent("Weather in Springfield.", defaultLocation);
    expect(springfieldQuery.scope).toBe("explicit_override");
    expect(springfieldQuery.effectiveLocation?.city).toBe("Springfield");

    // Travel to Paris
    const parisQuery = resolveLocationIntent("travel to Paris", defaultLocation);
    expect(parisQuery.scope).toBe("explicit_override");
    expect(parisQuery.effectiveLocation?.city).toBe("Paris");

    // General coding or math queries must be classified as unrelated
    const mathQuery = resolveLocationIntent("What is 42 * 17 + 89?", defaultLocation);
    expect(mathQuery.scope).toBe("unrelated");
    expect(mathQuery.effectiveLocation).toBeNull();
  });

  it("verifies ask_user structured questions normalize cleanly without plain text menus", () => {
    const questionPayload = {
      questions: [
        {
          question: "Which laptop operating system do you prefer?",
          options: ["macOS", "Linux", "Windows"],
        },
      ],
    };
    const normalized = normalizeAskUserInput(questionPayload);
    expect(normalized).not.toBeNull();
    expect(normalized?.[0]?.question).toBe("Which laptop operating system do you prefer?");
    expect(normalized?.[0]?.options).toHaveLength(3);
  });
});
